-- DECISION & REVIEW MICROSERVICE
-- Oracle Database Schema
--
-- Tables:
-- 1. KYC_DECISIONS
-- 2. REVIEW_CASES
--
-- Execute once using DECISION_DB_USERNAME (default KYC_DECISION) in SQL Developer.
-- Do not rerun CREATE statements on existing objects.
-- ==========================================================


-- ==========================================================
-- 1. KYC_DECISIONS
-- ==========================================================

CREATE TABLE KYC_DECISIONS (

    DECISION_ID NUMBER(19)
        GENERATED BY DEFAULT AS IDENTITY,

    APPLICATION_ID NUMBER(19) NOT NULL,

    VERIFICATION_ID VARCHAR2(36),

    STATUS VARCHAR2(40) NOT NULL,

    REASON VARCHAR2(1000),

    NAME_SCORE FLOAT,

    ADDRESS_SCORE FLOAT,

    CREATED_AT TIMESTAMP(6) WITH TIME ZONE NOT NULL,

    UPDATED_AT TIMESTAMP(6) WITH TIME ZONE NOT NULL,

    VERSION NUMBER(10) DEFAULT 0 NOT NULL,

    CONSTRAINT PK_KYC_DECISIONS
        PRIMARY KEY (DECISION_ID),

    CONSTRAINT UQ_DECISION_APPLICATION
        UNIQUE (APPLICATION_ID)
);


-- ==========================================================
-- 2. REVIEW_CASES
-- ==========================================================

CREATE TABLE REVIEW_CASES (

    REVIEW_ID NUMBER(19)
        GENERATED BY DEFAULT AS IDENTITY,

    APPLICATION_ID NUMBER(19) NOT NULL,

    VERIFICATION_ID VARCHAR2(36) NOT NULL,

    VERIFICATION_DECISION VARCHAR2(40) NOT NULL,

    REVIEW_STATE VARCHAR2(30) NOT NULL,

    TARGET_STATUS VARCHAR2(40),

    REASON VARCHAR2(1000),

    REVIEWER VARCHAR2(150),

    REQUESTED_DOCUMENT_TYPES VARCHAR2(200),

    OPERATION_REFERENCE VARCHAR2(100),

    EXPECTED_VERSION NUMBER(10),

    CUSTOMER_VERSION NUMBER(10),

    CREATED_AT TIMESTAMP(6) WITH TIME ZONE NOT NULL,

    UPDATED_AT TIMESTAMP(6) WITH TIME ZONE NOT NULL,

    ROW_VERSION NUMBER(19) DEFAULT 0 NOT NULL,

    CONSTRAINT PK_REVIEW_CASES
        PRIMARY KEY (REVIEW_ID),

    CONSTRAINT UQ_REVIEW_VERIFICATION
        UNIQUE (VERIFICATION_ID),

    CONSTRAINT UQ_REVIEW_OPERATION
        UNIQUE (OPERATION_REFERENCE),

    CONSTRAINT CK_REVIEW_STATE
        CHECK (
            REVIEW_STATE IN (
                'PENDING_SYNC',
                'OPEN',
                'COMPLETED',
                'SYNC_CONFLICT'
            )
        )
);


-- ==========================================================
-- 3. INDEXES FOR KYC_DECISIONS
-- ==========================================================

-- APPLICATION_ID already has a unique index
-- through UQ_DECISION_APPLICATION.

CREATE INDEX IDX_DECISION_STATUS
ON KYC_DECISIONS (STATUS);


-- ==========================================================
-- 4. INDEXES FOR REVIEW_CASES
-- ==========================================================

CREATE INDEX IDX_REVIEW_APPLICATION
ON REVIEW_CASES (
    APPLICATION_ID,
    CREATED_AT
);

CREATE INDEX IDX_REVIEW_STATE
ON REVIEW_CASES (
    REVIEW_STATE,
    CREATED_AT
);


-- ==========================================================
-- 5. PREVENT MULTIPLE ACTIVE REVIEW CASES
-- ==========================================================

CREATE UNIQUE INDEX UQ_ACTIVE_REVIEW_APPLICATION
ON REVIEW_CASES (
    CASE
        WHEN REVIEW_STATE IN (
            'PENDING_SYNC',
            'OPEN',
            'SYNC_CONFLICT'
        )
        THEN APPLICATION_ID
    END
);


