CREATE TABLE APP_USERS (
    USER_ID NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    EMAIL VARCHAR2(150) NOT NULL,
    PASSWORD_HASH VARCHAR2(255) NOT NULL,
    ROLE VARCHAR2(20) DEFAULT 'CUSTOMER' NOT NULL,
    ACCOUNT_STATUS VARCHAR2(20) DEFAULT 'ACTIVE' NOT NULL,
    CREATED_AT TIMESTAMP(6) DEFAULT SYS_EXTRACT_UTC(SYSTIMESTAMP) NOT NULL,
    CONSTRAINT UQ_APP_USERS_EMAIL UNIQUE (EMAIL),
    CONSTRAINT CK_APP_USER_ROLE CHECK (ROLE IN ('CUSTOMER','REVIEWER','ADMIN')),
    CONSTRAINT CK_APP_USER_STATUS CHECK (ACCOUNT_STATUS IN ('ACTIVE','LOCKED','DISABLED'))
);

CREATE TABLE CUSTOMERS (
    CUSTOMER_ID NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    USER_ID NUMBER(19) NOT NULL,
    FULL_NAME VARCHAR2(150) NOT NULL,
    DATE_OF_BIRTH DATE NOT NULL,
    MOBILE_NUMBER VARCHAR2(10) NOT NULL,
    ADDRESS VARCHAR2(300) NOT NULL,
    CITY VARCHAR2(100) NOT NULL,
    STATE VARCHAR2(100) NOT NULL,
    POSTAL_CODE VARCHAR2(12) NOT NULL,
    CREATED_AT TIMESTAMP(6) DEFAULT SYS_EXTRACT_UTC(SYSTIMESTAMP) NOT NULL,
    CONSTRAINT UQ_CUSTOMERS_USER UNIQUE (USER_ID),
    CONSTRAINT UQ_CUSTOMERS_MOBILE UNIQUE (MOBILE_NUMBER),
    CONSTRAINT FK_CUSTOMERS_USER FOREIGN KEY (USER_ID) REFERENCES APP_USERS(USER_ID)
);

CREATE TABLE KYC_APPLICATIONS (
    APPLICATION_ID NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    CUSTOMER_ID NUMBER(19) NOT NULL,
    APPLICATION_REF VARCHAR2(40) NOT NULL,
    APPLICANT_NAME VARCHAR2(150) NOT NULL,
    APPLICANT_DOB DATE NOT NULL,
    APPLICANT_ADDRESS VARCHAR2(300) NOT NULL,
    APPLICANT_CITY VARCHAR2(100),
    APPLICANT_STATE VARCHAR2(100),
    APPLICANT_POSTAL_CODE VARCHAR2(12),
    APPLICATION_STATUS VARCHAR2(40) DEFAULT 'DRAFT' NOT NULL,
    STATUS_REASON VARCHAR2(1000),
    REQUESTED_DOCUMENT_TYPES VARCHAR2(200),
    CREATED_AT TIMESTAMP(6) NOT NULL,
    SUBMITTED_AT TIMESTAMP(6),
    UPDATED_AT TIMESTAMP(6) NOT NULL,
    VERSION NUMBER(10) DEFAULT 0 NOT NULL,
    CONSTRAINT UQ_KYC_APP_REF UNIQUE (APPLICATION_REF),
    CONSTRAINT FK_KYC_APP_CUSTOMER FOREIGN KEY (CUSTOMER_ID) REFERENCES CUSTOMERS(CUSTOMER_ID),
    CONSTRAINT CK_KYC_APP_STATUS CHECK (APPLICATION_STATUS IN (
        'DRAFT','SUBMITTED','PROCESSING','AUTO_CHECKS_PASSED','MANUAL_REVIEW',
        'RESUBMISSION_REQUIRED','APPROVED','REJECTED','CANCELLED'))
);

-- A service-level exists check alone does not prevent concurrent creation.
CREATE UNIQUE INDEX UQ_ACTIVE_KYC_CUSTOMER ON KYC_APPLICATIONS (
    CASE WHEN APPLICATION_STATUS IN (
        'DRAFT','SUBMITTED','PROCESSING','AUTO_CHECKS_PASSED',
        'MANUAL_REVIEW','RESUBMISSION_REQUIRED')
    THEN CUSTOMER_ID END
);
CREATE INDEX IDX_KYC_CUSTOMER_CREATED ON KYC_APPLICATIONS(CUSTOMER_ID, CREATED_AT);

CREATE TABLE KYC_STATUS_OPERATIONS (
    OPERATION_ID NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    APPLICATION_ID NUMBER(19) NOT NULL,
    DECISION_REFERENCE VARCHAR2(100) NOT NULL,
    FROM_STATUS VARCHAR2(40) NOT NULL,
    TO_STATUS VARCHAR2(40) NOT NULL,
    REASON VARCHAR2(1000),
    REQUESTED_DOCUMENT_TYPES VARCHAR2(200),
    EXPECTED_VERSION NUMBER(10) NOT NULL,
    RESULT_VERSION NUMBER(10) NOT NULL,
    CREATED_AT TIMESTAMP(6) DEFAULT SYS_EXTRACT_UTC(SYSTIMESTAMP) NOT NULL,
    CONSTRAINT UQ_KYC_STATUS_REFERENCE UNIQUE (DECISION_REFERENCE),
    CONSTRAINT FK_STATUS_APPLICATION FOREIGN KEY (APPLICATION_ID)
        REFERENCES KYC_APPLICATIONS(APPLICATION_ID)
);
CREATE INDEX IDX_KYC_OPERATION_HISTORY ON KYC_STATUS_OPERATIONS(APPLICATION_ID, CREATED_AT);

