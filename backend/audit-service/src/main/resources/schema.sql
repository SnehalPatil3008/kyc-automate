CREATE TABLE AUDIT_EVENTS (
    EVENT_ID NUMBER(19) GENERATED BY DEFAULT AS IDENTITY,
    APPLICATION_ID VARCHAR2(36) NOT NULL,
    DOCUMENT_TYPE VARCHAR2(50),
    EVENT_TYPE VARCHAR2(50) NOT NULL,
    REASON VARCHAR2(2000),
    ACTOR VARCHAR2(255) NOT NULL,
    ACTOR_ROLE VARCHAR2(30) NOT NULL,
    EVENT_TIMESTAMP TIMESTAMP(6) WITH TIME ZONE
        DEFAULT SYSTIMESTAMP NOT NULL,

    CONSTRAINT PK_AUDIT_EVENTS
        PRIMARY KEY (EVENT_ID)
);